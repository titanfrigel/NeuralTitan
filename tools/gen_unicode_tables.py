"""Generates src/tokenizer/unicode_tables.{hpp,cpp}.

The pre-tokenizer needs three Unicode character classes: letters (\\p{L}),
numbers (\\p{N}) and whitespace (\\s). Letters and numbers come from
unicodedata.category over every code point; the White_Space list is short and
stable, so it is written out below. Each class is emitted as sorted, merged,
inclusive {first, last} ranges, searched by binary search in C++.

Run from the repository root, in the tools venv:

    tools/.venv/Scripts/python -I tools/gen_unicode_tables.py

The output depends only on the Unicode version of this Python's unicodedata,
which the generated files record.
"""

import pathlib
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "src" / "tokenizer"

LETTER_CATEGORIES = {"Lu", "Ll", "Lt", "Lm", "Lo"}
NUMBER_CATEGORIES = {"Nd", "Nl", "No"}

# The Unicode White_Space property (PropList.txt), as inclusive ranges.
WHITE_SPACE = [
    (0x0009, 0x000D),
    (0x0020, 0x0020),
    (0x0085, 0x0085),
    (0x00A0, 0x00A0),
    (0x1680, 0x1680),
    (0x2000, 0x200A),
    (0x2028, 0x2029),
    (0x202F, 0x202F),
    (0x205F, 0x205F),
    (0x3000, 0x3000),
]

HEADER_NOTE = (
    "// Generated by tools/gen_unicode_tables.py from Unicode {version}.\n"
    "// Do not edit; rerun the script instead.\n"
)


def ranges_of(categories):
    """Sorted, merged inclusive ranges of the code points in `categories`."""
    ranges = []
    for cp in range(0x110000):
        if unicodedata.category(chr(cp)) not in categories:
            continue
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return [tuple(r) for r in ranges]


def emit_table(name, ranges):
    lines = [f"constexpr CodePointRange {name}[] = {{"]
    for first, last in ranges:
        lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
    lines.append("};")
    return "\n".join(lines)


def header(version):
    return (
        HEADER_NOTE.format(version=version)
        + """
#pragma once

#include <string_view>

namespace titan::tokenizer {

// The Unicode version the tables were generated from.
inline constexpr std::string_view kUnicodeVersion = "@VERSION@";

// \\p{L}: general categories Lu, Ll, Lt, Lm and Lo.
bool is_letter(char32_t cp);

// \\p{N}: general categories Nd, Nl and No.
bool is_number(char32_t cp);

// The White_Space property, which is what \\s matches.
bool is_whitespace(char32_t cp);

}  // namespace titan::tokenizer
""".replace("@VERSION@", version)
    )


def source(version):
    tables = "\n\n".join(
        [
            emit_table("kLetters", ranges_of(LETTER_CATEGORIES)),
            emit_table("kNumbers", ranges_of(NUMBER_CATEGORIES)),
            emit_table("kWhiteSpace", WHITE_SPACE),
        ]
    )
    return (
        HEADER_NOTE.format(version=version)
        + """
#include "tokenizer/unicode_tables.hpp"

#include <algorithm>
#include <cstddef>
#include <iterator>

namespace titan::tokenizer {

namespace {

// An inclusive range of code points.
struct CodePointRange {
    char32_t first;
    char32_t last;
};

// One range per line, so a Unicode update reads as a small diff.
// clang-format off
"""
        + tables
        + """
// clang-format on

// The ranges are sorted and disjoint, so the only candidate is the first range
// whose last code point is >= cp.
template <std::size_t N>
bool in_ranges(const CodePointRange (&ranges)[N], char32_t cp) {
    const auto it = std::lower_bound(
        std::begin(ranges), std::end(ranges), cp,
        [](const CodePointRange& r, char32_t c) { return r.last < c; });
    return it != std::end(ranges) && it->first <= cp;
}

}  // namespace

bool is_letter(char32_t cp) { return in_ranges(kLetters, cp); }

bool is_number(char32_t cp) { return in_ranges(kNumbers, cp); }

bool is_whitespace(char32_t cp) { return in_ranges(kWhiteSpace, cp); }

}  // namespace titan::tokenizer
"""
    )


def main():
    version = unicodedata.unidata_version
    for name, text in (
        ("unicode_tables.hpp", header(version)),
        ("unicode_tables.cpp", source(version)),
    ):
        path = OUT_DIR / name
        path.write_text(text, encoding="utf-8", newline="\n")
        print(path)


if __name__ == "__main__":
    main()
