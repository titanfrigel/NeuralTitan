"""Generates src/tokenizer/unicode_tables.{hpp,cpp}.

The pre-tokenizer must classify characters exactly as the reference does:
Hugging Face tokenizers with SmolLM2's pre-tokenizer. Its two stages use
different Unicode data, both newer than Python's unicodedata:

- the Digits stage uses Rust's char::is_numeric;
- the ByteLevel stage runs the GPT-2 pattern in Oniguruma, with \\p{L}, \\p{N}
  and \\s.

So the classes are not computed from a Unicode database but probed from the
reference itself: every Unicode scalar value (U+0000..U+10FFFF without the
surrogates) goes through small probe strings, and the piece counts show its
class. Each class is emitted as sorted, merged, inclusive {first, last}
ranges, searched by binary search in C++.

Run from the repository root, in the tools venv:

    tools/.venv/Scripts/python -I tools/gen_unicode_tables.py

It also prints how each probed class differs from Python's unicodedata, as a
sanity check.
"""

import pathlib
import sys
import unicodedata

import tokenizers
from tokenizers import pre_tokenizers

REFERENCE_VERSION = "0.23.3"
SOURCE = f"probed from tokenizers {REFERENCE_VERSION}"

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "src" / "tokenizer"

# The Unicode White_Space property (PropList.txt), as inclusive ranges. The
# probed \s class must equal it; the script stops otherwise.
WHITE_SPACE = [
    (0x0009, 0x000D),
    (0x0020, 0x0020),
    (0x0085, 0x0085),
    (0x00A0, 0x00A0),
    (0x1680, 0x1680),
    (0x2000, 0x200A),
    (0x2028, 0x2029),
    (0x202F, 0x202F),
    (0x205F, 0x205F),
    (0x3000, 0x3000),
]

HEADER_NOTE = (
    f"// Generated by tools/gen_unicode_tables.py, {SOURCE}.\n"
    "// Do not edit; rerun the script instead.\n"
)


def scalar_values():
    """Every Unicode scalar value: U+0000..U+10FFFF without the surrogates."""
    for cp in range(0x110000):
        if not 0xD800 <= cp <= 0xDFFF:
            yield cp


class Probe:
    """The reference's character classes, read from piece counts."""

    def __init__(self):
        self.digits = pre_tokenizers.Digits(individual_digits=True)
        self.byte_level = pre_tokenizers.ByteLevel(
            add_prefix_space=False, use_regex=True
        )

    @staticmethod
    def count(pre_tokenizer, text):
        return len(pre_tokenizer.pre_tokenize_str(text))

    def is_numeric(self, ch):
        # Digits isolates a number: "a" ch "a" gives a, ch, a. Anything else
        # leaves the string whole.
        return self.count(self.digits, "a" + ch + "a") == 3

    def is_letter(self, ch):
        # " ?\p{L}+" joins a letter to the "a" before it; any other class
        # starts a new piece.
        return self.count(self.byte_level, "a" + ch) == 1

    def is_number(self, ch):
        # " ?\p{N}+" joins a number to the "1" before it.
        return self.count(self.byte_level, "1" + ch) == 1

    def is_whitespace(self, ch):
        # "\s+(?!\S)" takes ch "\n" whole when ch is whitespace. A letter, a
        # number or an "other" character is a piece of its own before "\n".
        return self.count(self.byte_level, ch + "\n") == 1


def check_probe(probe):
    """Checks each probe on characters whose class is known."""
    known = {
        "letter": ("a", "Z", "é", "日", "م"),
        "number": ("7", "١", "Ⅻ", "½"),
        "whitespace": (" ", "\n", "\t", " ", "　", " "),
        "other": ("_", "'", "!", "\U0001f642"),
    }
    tests = {
        "letter": probe.is_letter,
        "number": probe.is_number,
        "whitespace": probe.is_whitespace,
    }
    for cls, chars in known.items():
        for ch in chars:
            for name, test in tests.items():
                assert test(ch) == (name == cls), (name, ascii(ch))
            assert probe.is_numeric(ch) == (cls == "number"), ascii(ch)


def to_ranges(code_points):
    """Sorted, merged inclusive ranges of a set of code points."""
    ranges = []
    for cp in sorted(code_points):
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return [tuple(r) for r in ranges]


def from_ranges(ranges):
    return {cp for first, last in ranges for cp in range(first, last + 1)}


def unicodedata_class(categories):
    return {
        cp
        for cp in scalar_values()
        if unicodedata.category(chr(cp)) in categories
    }


def report_differences(classes):
    """Prints how the probed classes differ from Python's unicodedata."""
    letters = unicodedata_class({"Lu", "Ll", "Lt", "Lm", "Lo"})
    numbers = unicodedata_class({"Nd", "Nl", "No"})
    print(f"compared with unicodedata {unicodedata.unidata_version}:")
    for name, expected in (
        ("is_letter", letters),
        ("is_number", numbers),
        ("is_numeric", numbers),
        ("is_whitespace", from_ranges(WHITE_SPACE)),
    ):
        probed = classes[name]
        print(
            f"  {name}: {len(probed)} code points, "
            f"{len(probed - expected)} added, {len(expected - probed)} removed"
        )
    only_numeric = classes["is_numeric"] - classes["is_number"]
    only_number = classes["is_number"] - classes["is_numeric"]
    print(
        f"  is_numeric vs is_number: {len(only_numeric)} only in is_numeric, "
        f"{len(only_number)} only in is_number"
    )


def emit_table(name, ranges):
    lines = [f"constexpr CodePointRange {name}[] = {{"]
    for first, last in ranges:
        lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
    lines.append("};")
    return "\n".join(lines)


def header():
    return (
        HEADER_NOTE
        + """
#pragma once

#include <string_view>

namespace titan::tokenizer {

// Where the tables come from: the reference implementation itself, so that
// they match its Unicode version exactly.
inline constexpr std::string_view kUnicodeSource =
    "@SOURCE@";

// \\p{L} as the GPT-2 pattern matches it (Oniguruma): letters.
bool is_letter(char32_t cp);

// \\p{N} as the GPT-2 pattern matches it (Oniguruma): numbers.
bool is_number(char32_t cp);

// The numbers the Digits stage isolates (Rust's char::is_numeric). Its
// Unicode version differs from Oniguruma's, so this is not is_number.
bool is_numeric(char32_t cp);

// \\s as the GPT-2 pattern matches it: the White_Space property.
bool is_whitespace(char32_t cp);

}  // namespace titan::tokenizer
""".replace("@SOURCE@", SOURCE)
    )


def source(classes):
    tables = "\n\n".join(
        [
            emit_table("kLetters", to_ranges(classes["is_letter"])),
            emit_table("kNumbers", to_ranges(classes["is_number"])),
            emit_table("kNumeric", to_ranges(classes["is_numeric"])),
            emit_table("kWhiteSpace", WHITE_SPACE),
        ]
    )
    return (
        HEADER_NOTE
        + """
#include "tokenizer/unicode_tables.hpp"

#include <algorithm>
#include <cstddef>
#include <iterator>

namespace titan::tokenizer {

namespace {

// An inclusive range of code points.
struct CodePointRange {
    char32_t first;
    char32_t last;
};

// One range per line, so a Unicode update reads as a small diff.
// clang-format off
"""
        + tables
        + """
// clang-format on

// The ranges are sorted and disjoint, so the only candidate is the first range
// whose last code point is >= cp.
template <std::size_t N>
bool in_ranges(const CodePointRange (&ranges)[N], char32_t cp) {
    const auto it = std::lower_bound(
        std::begin(ranges), std::end(ranges), cp,
        [](const CodePointRange& r, char32_t c) { return r.last < c; });
    return it != std::end(ranges) && it->first <= cp;
}

}  // namespace

bool is_letter(char32_t cp) { return in_ranges(kLetters, cp); }

bool is_number(char32_t cp) { return in_ranges(kNumbers, cp); }

bool is_numeric(char32_t cp) { return in_ranges(kNumeric, cp); }

bool is_whitespace(char32_t cp) { return in_ranges(kWhiteSpace, cp); }

}  // namespace titan::tokenizer
"""
    )


def main():
    if tokenizers.__version__ != REFERENCE_VERSION:
        sys.exit(
            f"gen_unicode_tables: tokenizers {tokenizers.__version__} is "
            f"installed, the tables are pinned to {REFERENCE_VERSION}"
        )
    probe = Probe()
    check_probe(probe)

    classes = {name: set() for name in
               ("is_letter", "is_number", "is_numeric", "is_whitespace")}
    for cp in scalar_values():
        ch = chr(cp)
        for name, members in classes.items():
            if getattr(probe, name)(ch):
                members.add(cp)

    # The regex classes must be disjoint, as the scanner assumes.
    assert not classes["is_letter"] & classes["is_number"]
    assert not classes["is_letter"] & classes["is_whitespace"]
    assert not classes["is_number"] & classes["is_whitespace"]
    # pretokenize relies on the Digits stage isolating every \p{N} number.
    assert classes["is_number"] <= classes["is_numeric"]
    if classes["is_whitespace"] != from_ranges(WHITE_SPACE):
        sys.exit("gen_unicode_tables: the probed \\s differs from WHITE_SPACE")

    for name, text in (
        ("unicode_tables.hpp", header()),
        ("unicode_tables.cpp", source(classes)),
    ):
        path = OUT_DIR / name
        path.write_text(text, encoding="utf-8", newline="\n")
        print(path)
    report_differences(classes)


if __name__ == "__main__":
    main()
